"""Builds lib/muscle_data.dart from two open exercise databases (run from the repo root):

    python tool/exercise_muscles.py

- free-exercise-db (github.com/yuhonas/free-exercise-db, public domain): 17 muscles per exercise,
  English names only.
- wger.de (CC-BY-SA 3.0/4.0, CC0): German and English names, coarser muscles.

Every name (wger German/English/aliases, free-exercise-db English) becomes a key, normalized like
searchKey in lib/model.dart, with its primary and secondary muscles as bit masks in Muscle order
(lib/muscles.dart). A wger exercise takes the muscles of the free-exercise-db exercise with the most
similar English name when the names are close and the body regions agree; else its own, mapped.
"""
import json, re, urllib.request

# = Muscle order in lib/muscles.dart, with the region each belongs to
MUSCLES = [('chest', 'chest'), ('shoulders', 'shoulders'), ('triceps', 'arms'), ('biceps', 'arms'),
           ('forearms', 'arms'), ('lats', 'back'), ('middle back', 'back'), ('lower back', 'back'),
           ('traps', 'back'), ('neck', 'back'), ('abdominals', 'core'), ('quadriceps', 'legs'),
           ('hamstrings', 'legs'), ('glutes', 'legs'), ('calves', 'legs'), ('adductors', 'legs'),
           ('abductors', 'legs')]
NAMES = [m for m, _ in MUSCLES]
REGION = dict(MUSCLES)
# wger muscle id -> muscle
WGER = {1: 'biceps', 13: 'biceps', 5: 'triceps', 2: 'shoulders', 3: 'chest', 4: 'chest', 12: 'lats', 9: 'traps',
        10: 'quadriceps', 11: 'hamstrings', 8: 'glutes', 7: 'calves', 15: 'calves', 6: 'abdominals', 14: 'abdominals'}
# wger category, for exercises without muscles; the vague ones (Legs, Back, Arms) are left out
CATEGORY = {'Abs': 'abdominals', 'Calves': 'calves', 'Chest': 'chest', 'Shoulders': 'shoulders'}
GERMAN, ENGLISH = 1, 2


def get(url):
    with urllib.request.urlopen(url) as r:
        return json.load(r)


def key(s):
    s = s.lower().replace('ä', 'ae').replace('ö', 'oe').replace('ü', 'ue').replace('ß', 'ss')
    return re.sub('[^a-z0-9]', '', s)


STOP = {'with', 'the', 'a', 'on', 'to', 'and', 'of', 'in', 'single', 'arm', 'one'}
SAME = {'dumbbells': 'dumbbell', 'db': 'dumbbell', 'barbells': 'barbell', 'bb': 'barbell', 'benchpress': 'bench press'}


def words(name):
    s = re.sub('[-()]', ' ', name.lower())
    for a, b in SAME.items():
        s = re.sub(rf'\b{a}\b', b, s)
    return {w.rstrip('s') for w in re.findall('[a-z]+', s)} - STOP


def bits(muscles):
    return sum(1 << NAMES.index(m) for m in set(muscles))


def regions(muscles):
    return {REGION[m] for m in muscles}


free = [e for e in get('https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json')
        if e['category'] != 'stretching' and e['primaryMuscles']]
free_words = [(words(e['name']), e) for e in free]
wger = get('https://wger.de/api/v2/exerciseinfo/?limit=2000')['results']

out, matched = {}, 0
for e in wger:
    primary = {WGER[m['id']] for m in e['muscles']} or {CATEGORY.get(e['category']['name'])} - {None}
    if not primary:
        continue  # cardio or too vague
    secondary = {WGER[m['id']] for m in e['muscles_secondary']} - primary
    english = [t['name'] for t in e['translations'] if t['language'] == ENGLISH]
    if english:
        w = words(english[0])
        # Similar names; a name fully inside a longer one counts too ("Hyperextensions" in
        # "Hyperextensions (Back Extensions)").
        score, best = max(((1 if w and w <= fw else len(w & fw) / len(w | fw), f) for fw, f in free_words),
                          key=lambda x: x[0])
        if score >= .6 and regions(best['primaryMuscles']) & regions(primary):
            primary, secondary = set(best['primaryMuscles']), set(best['secondaryMuscles']) - set(best['primaryMuscles'])
            matched += 1
    for t in e['translations']:
        if t['language'] in (GERMAN, ENGLISH):
            for name in [t['name']] + [a['alias'] for a in t.get('aliases', [])]:
                if (k := key(name)) and k not in out:
                    out[k] = (bits(primary), bits(secondary))
for f in free:
    out.setdefault(key(f['name']), (bits(f['primaryMuscles']), bits(set(f['secondaryMuscles']) - set(f['primaryMuscles']))))

lines = ''.join(f"  '{k}': ({p}, {s}),\n" for k, (p, s) in sorted(out.items()))
open('lib/muscle_data.dart', 'w').write(
    '// Generated by tool/exercise_muscles.py, do not edit.\n'
    '// Sources: free-exercise-db (public domain) and wger.de (CC-BY-SA 3.0/4.0, CC0).\n\n'
    '/// searchKey(exercise name) -> (primary, secondary) muscles as bits in Muscle order.\n'
    f'const exerciseMuscles = <String, (int, int)>{{\n{lines}}};\n')
print(len(out), 'names,', matched, 'wger exercises refined by free-exercise-db')
